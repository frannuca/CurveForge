# Logger-name prefixes for this project's own model/training/data code (every module here
# uses `logging.getLogger(__name__)`, so these match exactly). Attaching `ModelOnlyFilter`
# to the dashboard's log handler keeps the browser's log panel to lines that actually
# describe what a run is doing, dropping infrastructure noise that would otherwise flood it —
# Werkzeug's per-request access log (one line per `dcc.Interval` poll while a job runs),
# urllib3/psycopg connection chatter, matplotlib font-cache messages, and the like.
MODEL_LOG_PREFIXES = ("main_lstm", "optimize_hyperparams", "pretrain_autoencoder", "simple_lstm", "fx_forecasting")


class ModelOnlyFilter(logging.Filter):
    """Keeps only records from `MODEL_LOG_PREFIXES` loggers."""

    def filter(self, record: logging.LogRecord) -> bool:
        return record.name.startswith(MODEL_LOG_PREFIXES)


class ListLogHandler(logging.Handler):
    """Appends formatted log records to a plain list, polled by the UI."""

    def __init__(self, sink: list[str]) -> None:
        super().__init__()
        self.sink = sink
        self.setFormatter(logging.Formatter("%(asctime)s %(levelname)s %(message)s"))
        self.addFilter(ModelOnlyFilter())

    def emit(self, record: logging.LogRecord) -> None:
        self.sink.append(self.format(record))


RUN_STATE: dict[str, dict[str, Any]] = {
    "train": {"thread": None, "logs": [], "running": False, "error": None, "artifacts": {}, "cancelled": False},
    "optimize": {
        "thread": None,
        "logs": [],
        "running": False,
        "error": None,
        "artifacts": {},
        "progress_total_estimate": None,
        "cancelled": False,
    },
    "pretrain": {"thread": None, "logs": [], "running": False, "error": None, "artifacts": {}, "cancelled": False},
}

# Each mode's cooperative-cancellation flag, checked from inside the running
# job itself (main_lstm.train()'s epoch loop / optimize_hyperparams's DE
# objective / pretrain_autoencoder.train_autoencoder()'s epoch loop) — a
# thread can't be safely force-killed, so Stop just requests cancellation at
# the next safe checkpoint rather than stopping instantly.
CANCEL_EVENTS: dict[str, threading.Event] = {
    "train": main_lstm.CANCEL_EVENT,
    "optimize": optimize_hyperparams.CANCEL_EVENT,
    "pretrain": pretrain_autoencoder.CANCEL_EVENT,
}


def run_job(mode: str, entry_fn: Callable[[list[str] | None], None], argv: list[str]) -> None:
    state = RUN_STATE[mode]
    handler = ListLogHandler(state["logs"])
    root_logger = logging.getLogger()
    root_logger.addHandler(handler)
    root_logger.setLevel(logging.INFO)
    state["logs"].append("$ " + " ".join(argv))
    try:
        entry_fn(argv)
    except SystemExit as e:
        if not state["cancelled"]:
            state["error"] = f"Argument error (exit code {e.code}) — check the log above."
    except Exception as e:  # noqa: BLE001 — surface any failure to the UI rather than losing it
        if state["cancelled"]:
            # Both scripts cancel gracefully (main_lstm.train() breaks its epoch loop;
            # optimize_hyperparams's DE callback returns True) — entry_fn returns
            # normally rather than raising, so this branch is a defensive fallback,
            # not the expected path for a user-requested stop.
            state["logs"].append(f"{type(e).__name__}: {e} (occurred while a stop was requested)")
        else:
            state["error"] = f"{type(e).__name__}: {e}"
            state["logs"].append(traceback.format_exc())
    finally:
        root_logger.removeHandler(handler)
        state["running"] = False


def start_job(mode: str, entry_fn: Callable[[list[str] | None], None], argv: list[str]) -> None:
    state = RUN_STATE[mode]
    if state["running"]:
        return
    CANCEL_EVENTS[mode].clear()
    state.update(
        thread=None, logs=[], running=True, error=None, artifacts={}, progress_total_estimate=None, cancelled=False
    )
    thread = threading.Thread(target=run_job, args=(mode, entry_fn, argv), daemon=True)
    state["thread"] = thread
    thread.start()


def stop_job(mode: str) -> None:
    """Requests cancellation of the running job for `mode`; takes effect at the next
    safe checkpoint inside the job (not instantly — see `CANCEL_EVENTS`)."""
    state = RUN_STATE[mode]
    if state["running"]:
        state["cancelled"] = True
        CANCEL_EVENTS[mode].set()


def resolve_default(parser: argparse.ArgumentParser, dest: str) -> Any:
    for action in parser._actions:  # noqa: SLF001 — argparse has no public accessor for this
        if action.dest == dest:
            return action.default
    return None


def build_argv(parser: argparse.ArgumentParser, values: dict[str, Any]) -> list[str]:
    """Turns {dest: form_value} into a CLI argv list, letting empty fields fall back to
    each flag's own script default (by simply omitting that flag)."""
    argv: list[str] = []
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, argparse._HelpAction):  # noqa: SLF001
            continue
        dest = action.dest
        if dest not in values:
            continue
        value = values[dest]
        flag = action.option_strings[0]

        if isinstance(action, (argparse._StoreTrueAction, argparse._StoreFalseAction)):  # noqa: SLF001
            if value:  # dcc.Checklist value is a list, e.g. ["on"] or []
                argv.append(flag)
            continue

        if value is None or value == "" or value == []:
            continue

        if action.nargs == "+":
            argv.append(flag)
            argv.extend(str(v) for v in value)
            continue

        argv.append(flag)
        argv.append(str(value))
    return argv


def render_interactive_plot(csv_path: str | None, kind: str, title: str):
    """Builds an interactive (zoomable, hoverable) Plotly figure from a `main_lstm.py`-written
    sidecar CSV (see `plot_predictions_grid`/`log_and_plot_strategy_pnl`), replacing the older
    static-PNG-embedding approach — Plotly's own default box-zoom/scroll-zoom/pan and
    hover-on-cursor-move tooltip need no extra code beyond building the figure and returning it
    inside a `dcc.Graph`.

    `kind`: `"predictions"` (CSV columns `date, symbol, actual, predicted`), `"pnl"` (CSV
    columns `date, symbol, net_cumulative`), or `"positions"` (CSV columns `date, symbol,
    position, daily_return, pnl_with_costs, pnl_without_costs`, from
    `main_lstm.plot_positions_and_pnl` — position/return on the left axis, both PnL curves on
    a secondary right axis, mirroring that plot's `ax.twinx()`) — selects which column(s)
    become traces. One subplot row per symbol, mirroring the static PNG's
    one-panel-per-symbol layout (`"pnl"`'s pooled series arrives as an ordinary `symbol="ALL"`
    row, so it gets its own panel too, just like the PNG's final comparison panel).
    """
    if not csv_path or not Path(csv_path).exists():
        return None
    try:
        df = pd.read_csv(csv_path, parse_dates=["date"])
    except Exception:  # noqa: BLE001
        return None
    if df.empty:
        return None

    symbols = list(dict.fromkeys(df["symbol"]))  # de-duplicated, CSV's own (insertion) order
    fig = make_subplots(
        rows=len(symbols), cols=1, shared_xaxes=False, subplot_titles=symbols,
        specs=[[{"secondary_y": True}] for _ in symbols],
    )

    for i, symbol in enumerate(symbols, start=1):
        rows = df[df["symbol"] == symbol]
        if kind == "predictions":
            fig.add_trace(
                go.Scatter(
                    x=rows["date"], y=rows["actual"], name="actual", mode="lines",
                    legendgroup="actual", showlegend=(i == 1), line={"color": "#1f77b4"},
                ),
                row=i, col=1,
            )
            fig.add_trace(
                go.Scatter(
                    x=rows["date"], y=rows["predicted"], name="predicted", mode="lines",
                    legendgroup="predicted", showlegend=(i == 1), line={"color": "#ff7f0e"},
                ),
                row=i, col=1,
            )
        elif kind == "positions":
            fig.add_trace(
                go.Scatter(
                    x=rows["date"], y=rows["position"], name="position", mode="lines",
                    line_shape="hv", legendgroup="position", showlegend=(i == 1), line={"color": "#1f77b4"},
                ),
                row=i, col=1, secondary_y=False,
            )
            fig.add_trace(
                go.Scatter(
                    x=rows["date"], y=rows["daily_return"], name="daily return", mode="lines",
                    legendgroup="daily_return", showlegend=(i == 1), line={"color": "#888888", "width": 1},
                ),
                row=i, col=1, secondary_y=False,
            )
            fig.add_trace(
                go.Scatter(
                    x=rows["date"], y=rows["pnl_with_costs"], name="PnL (with costs)", mode="lines",
                    legendgroup="pnl_with", showlegend=(i == 1), line={"color": "#2b8a3e"},
                ),
                row=i, col=1, secondary_y=True,
            )
            fig.add_trace(
                go.Scatter(
                    x=rows["date"], y=rows["pnl_without_costs"], name="PnL (no costs)", mode="lines",
                    legendgroup="pnl_without", showlegend=(i == 1), line={"color": "#ff7f0e", "dash": "dash"},
                ),
                row=i, col=1, secondary_y=True,
            )
        else:
            fig.add_trace(
                go.Scatter(
                    x=rows["date"], y=rows["net_cumulative"], name=symbol, mode="lines",
                    showlegend=False, line={"color": "#2b8a3e" if symbol == "ALL" else "#1f77b4"},
                ),
                row=i, col=1,
            )

    fig.update_layout(
        title=title, height=max(260, 220 * len(symbols)), hovermode="x unified",
        margin={"l": 50, "r": 20, "t": 60, "b": 40},
    )
    return dcc.Graph(figure=fig, config={"scrollZoom": True, "displayModeBar": True})


def render_progress_bar(label: str, percent: float | None):
    """A minimal CSS progress bar — Dash core components has no built-in one."""
    if percent is None:
        return html.Div()
    percent = max(0.0, min(100.0, percent))
    return html.Div(
        [
            html.Div(label, style={"fontSize": "0.8rem", "marginBottom": "3px"}),
            html.Div(
                html.Div(
                    style={
                        "width": f"{percent}%",
                        "background": "#2b8a3e",
                        "height": "100%",
                        "borderRadius": "4px",
                        "transition": "width 0.4s ease",
                    }
                ),
                style={
                    "background": "#e0e0e0",
                    "height": "14px",
                    "borderRadius": "4px",
                    "overflow": "hidden",
                    "width": "100%",
                },
            ),
        ],
        style={"margin": "8px 0", "maxWidth": "420px"},
    )


def train_progress(state: dict[str, Any]):
    """Parses the last "epoch N/M" log line — --epochs is the exact, known denominator."""
    for line in reversed(state["logs"]):
        m = EPOCH_LOG_RE.search(line)
        if m:
            current, total = int(m.group(1)), int(m.group(2))
            return render_progress_bar(f"Epoch {current}/{total}", 100.0 * current / total)
    return html.Div()


def optimize_progress(state: dict[str, Any]):
    """Progress derived from the results CSV's row count, not the captured log text.

    With `--workers` > 1, each trial runs in a separate worker *process*
    (scipy's DE multiprocessing) — those processes have no logging handler
    attached (only the main process does, via `ListLogHandler`), so per-trial
    "trial N: ..." log lines never reach `state["logs"]` and a log-based
    progress bar would silently never move. The results CSV, on the other
    hand, is appended to directly by every worker regardless of process
    boundary (see `optimize_hyperparams.append_trial_row`), so it's the one
    reliable, process-agnostic signal for "how many trials have finished so
    far". Total trial count is only an estimate (DE's exact evaluation count
    depends on convergence), hence the "~".
    """
    csv_path = state.get("artifacts", {}).get("results_csv")
    if not csv_path or not Path(csv_path).exists():
        return html.Div()
    try:
        with open(csv_path, newline="") as f:
            current = sum(1 for _ in f) - 1  # total lines minus the header row
    except OSError:
        return html.Div()
    if current < 0:
        return html.Div()

    total = state.get("progress_total_estimate")
    if not total:
        return html.Div(f"Trial {current}")
    return render_progress_bar(f"Trial {current} / ~{total}", 100.0 * current / total)


