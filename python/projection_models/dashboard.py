def field_component(action: argparse.Action, id_prefix: str):
    dest = action.dest
    comp_id = {"type": f"{id_prefix}-field", "dest": dest}

    if isinstance(action, argparse._StoreTrueAction):  # noqa: SLF001
        return dcc.Checklist(id=comp_id, options=[{"label": " enabled", "value": "on"}], value=[])

    if action.choices:
        return dcc.Dropdown(id=comp_id, options=list(action.choices), value=action.default, clearable=False)

    if action.nargs == "+":
        options = PAIR_OPTIONS if dest == "pairs" else PARAM_OPTIONS if dest == "params" else []
        return dcc.Dropdown(id=comp_id, options=options, value=action.default or [], multi=True)

    if action.type in (int, float):
        return dcc.Input(
            id=comp_id, type="number", value=action.default, step="any", style={"width": "100%"}
        )

    return dcc.Input(
        id=comp_id,
        type="text",
        value=action.default if action.default is not None else "",
        placeholder=str(action.default) if action.default is not None else "",
        style={"width": "100%"},
    )


def build_form(parser: argparse.ArgumentParser, id_prefix: str) -> list:
    cells = []
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, argparse._HelpAction):  # noqa: SLF001
            continue
        flag = action.option_strings[0]
        cells.append(
            html.Div(
                [
                    html.Label(flag, style={"fontWeight": "600", "fontSize": "0.85rem"}),
                    field_component(action, id_prefix),
                    html.Div(action.help or "", style={"fontSize": "0.72rem", "color": "#666", "marginTop": "2px"}),
                ],
                style={"padding": "8px"},
            )
        )
    return cells


