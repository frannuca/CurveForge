def register_run_callback(mode: str, parser: argparse.ArgumentParser, entry_fn) -> None:
    @app.callback(
        Output(f"{mode}-interval", "disabled"),
        Output(f"{mode}-status", "children"),
        Input(f"{mode}-run-btn", "n_clicks"),
        State({"type": f"{mode}-field", "dest": ALL}, "value"),
        State({"type": f"{mode}-field", "dest": ALL}, "id"),
        prevent_initial_call=True,
    )
    def on_run(n_clicks, values, ids):  # noqa: ANN001, ARG001
        if RUN_STATE[mode]["running"]:
            return False, "Already running…"
        value_map = {id_["dest"]: v for id_, v in zip(ids, values)}
        argv = build_argv(parser, value_map)

        artifacts: dict[str, str] = {}
        if mode == "train":
            artifacts["plot_path"] = value_map.get("plot_path") or resolve_default(parser, "plot_path")
            artifacts["in_sample_plot_path"] = value_map.get("in_sample_plot_path") or resolve_default(
                parser, "in_sample_plot_path"
            )
            artifacts["pnl_plot_path"] = value_map.get("pnl_plot_path") or resolve_default(parser, "pnl_plot_path")
        else:
            results_csv = value_map.get("load") or value_map.get("results_csv") or resolve_default(
                parser, "results_csv"
            )
            artifacts["results_csv"] = results_csv
            artifacts["best_plot_path"] = best_plot_path_for(results_csv) if results_csv else None

        start_job(mode, entry_fn, argv)
        RUN_STATE[mode]["artifacts"] = artifacts

        if mode == "optimize":
            # DE evaluates the objective ~popsize * num_params times per generation,
            # across maxiter+1 generations — an estimate (exact count depends on
            # convergence), used only to label the progress bar with "~".
            num_params = len(value_map.get("params") or [s.name for s in DEFAULT_PARAM_SPECS])
            popsize = int(value_map.get("popsize") or resolve_default(parser, "popsize"))
            maxiter = int(value_map.get("maxiter") or resolve_default(parser, "maxiter"))
            RUN_STATE[mode]["progress_total_estimate"] = popsize * num_params * (maxiter + 1)

        return False, "Running…"


register_run_callback("train", train_parser, main_lstm.main)
register_run_callback("optimize", optimize_parser, optimize_hyperparams.main)


def register_stop_callback(mode: str) -> None:
    @app.callback(
        Output(f"{mode}-status", "children", allow_duplicate=True),
        Input(f"{mode}-stop-btn", "n_clicks"),
        prevent_initial_call=True,
    )
    def on_stop(n_clicks):  # noqa: ANN001, ARG001
        if not RUN_STATE[mode]["running"]:
            return "Idle."
        stop_job(mode)
        return "Stopping…"


register_stop_callback("train")
register_stop_callback("optimize")


def render_train_artifacts(artifacts: dict[str, str]) -> list:
    children = []
    for key, title in (
        ("plot_path", "Out-of-sample (validation) predictions"),
        ("in_sample_plot_path", "In-sample (training) predictions"),
        ("pnl_plot_path", "Strategy PnL (out-of-sample)"),
    ):
        src = encode_image(artifacts.get(key))
        if src:
            children.append(html.H4(title))
            children.append(html.Img(src=src, style={"maxWidth": "100%"}))
    return children


def render_optimize_artifacts(artifacts: dict[str, str]) -> list:
    """Best-trial-so-far predictions plot (updated live by `optimize_hyperparams.
    maybe_save_best_prediction_plot` whenever a trial beats every prior one), then the
    top-10-by-loss table from the results CSV — both refreshed on every poll tick,
    including while the search is still running (see `register_poll_callback`)."""
    children = []

    best_plot_src = encode_image(artifacts.get("best_plot_path"))
    if best_plot_src:
        children.append(html.H4("Best trial so far — out-of-sample predictions"))
        children.append(html.Img(src=best_plot_src, style={"maxWidth": "100%"}))

    csv_path = artifacts.get("results_csv")
    if not csv_path or not Path(csv_path).exists():
        return children
    try:
        df = pd.read_csv(csv_path)
    except Exception:  # noqa: BLE001
        return children
    df = df[df["status"] == "ok"].sort_values("loss").head(10)
    if df.empty:
        children.append(html.Div("No successful trials in results CSV yet."))
        return children

    header = html.Tr([html.Th(c) for c in df.columns])
    rows = [html.Tr([html.Td(f"{v:.4g}" if isinstance(v, float) else v) for v in row]) for row in df.itertuples(index=False)]
    children.append(html.H4(f"Top {len(df)} trials — {csv_path}"))
    children.append(
        html.Table(
            [html.Thead(header), html.Tbody(rows)],
            style={"fontSize": "0.8rem", "borderCollapse": "collapse", "width": "100%"},
        )
    )
    return children


def register_poll_callback(mode: str, render_artifacts, progress_fn) -> None:
    @app.callback(
        Output(f"{mode}-log", "children"),
        Output(f"{mode}-status", "children", allow_duplicate=True),
        Output(f"{mode}-interval", "disabled", allow_duplicate=True),
        Output(f"{mode}-artifacts", "children"),
        Output(f"{mode}-progress", "children"),
        Input(f"{mode}-interval", "n_intervals"),
        prevent_initial_call=True,
    )
    def on_tick(_n_intervals):  # noqa: ANN001
        state = RUN_STATE[mode]
        log_text = "\n".join(state["logs"])
        progress = progress_fn(state)
        # Rendered every tick, running or not, so e.g. optimize_hyperparams's
        # best-trial-so-far plot updates live during a long search rather than
        # only appearing once the whole run finishes.
        artifacts_children = render_artifacts(state["artifacts"])
        if state["running"]:
            status = "Stopping…" if state["cancelled"] else "Running…"
            return log_text, status, False, artifacts_children, progress

        if state["cancelled"]:
            status = "Stopped by user."
        elif state["error"]:
            status = f"Failed: {state['error']}"
        else:
            status = "Done."
        return log_text, status, True, artifacts_children, progress


register_poll_callback("train", render_train_artifacts, train_progress)
register_poll_callback("optimize", render_optimize_artifacts, optimize_progress)


