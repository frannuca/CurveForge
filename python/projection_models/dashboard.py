"""Dash front-end for `pretrain_autoencoder.py` (cross-asset factor autoencoder
pretraining), `main_lstm.py` (train/evaluate), and `optimize_hyperparams.py`
(hyperparameter search via differential evolution).

Each tab's form is generated by introspecting that script's own
`argparse.ArgumentParser` (via `build_parser()`), so every CLI parameter is
exposed automatically and the UI can't drift out of sync with the scripts as
they evolve — nothing about individual flags is hardcoded here. Runs execute
in a background thread (training/search can take a while); a polling
`dcc.Interval` streams the captured log output back to the browser and shows
the resulting plots/results table once the run finishes.

Run:
    uv run python dashboard.py
Then open http://127.0.0.1:8050/
"""

